import assert from 'node:assert/strict';
import { chromium } from 'playwright';

const baseUrl = process.env.UI_TEST_URL ?? 'http://127.0.0.1:5173';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
const failures = [];
const dialogs = [];
const failedResponses = [];
const modelResponses = [];
const modelKind = process.env.SEGMENTATION_MODEL ?? 'universal';
page.on('pageerror', (error) => failures.push(error.message));
page.on('console', (message) => { if (message.type() === 'error') failures.push(message.text()); });
page.on('response', (response) => {
  if (response.status() >= 400) failedResponses.push({ status: response.status(), url: response.url() });
  if (response.url().includes('/models/')) modelResponses.push({ status: response.status(), url: response.url(), contentType: response.headers()['content-type'] });
});
page.on('dialog', async (dialog) => { dialogs.push(dialog.message()); await dialog.accept(); });
try {
  const response = await page.goto(baseUrl, { waitUntil: 'networkidle', timeout: 30_000 });
  assert.equal(response?.status(), 200);
  await page.waitForSelector('canvas');
  await page.locator('.rail-bottom .rail-button').first().click();
  await page.waitForTimeout(800);
  await page.locator('.save-state:not(.saving)').waitFor({ state: 'visible', timeout: 20_000 });
  const imageData = await page.evaluate(() => {
    const canvas = document.createElement('canvas');
    canvas.width = 256;
    canvas.height = 320;
    const context = canvas.getContext('2d');
    if (!context) throw new Error('Canvas unavailable');
    const background = context.createLinearGradient(0, 0, 256, 320);
    background.addColorStop(0, '#d5d9dc');
    background.addColorStop(1, '#8b9b9b');
    context.fillStyle = background;
    context.fillRect(0, 0, 256, 320);
    context.fillStyle = '#2f3438';
    context.beginPath();
    context.ellipse(128, 77, 43, 52, 0, 0, Math.PI * 2);
    context.fill();
    context.beginPath();
    context.moveTo(38, 310);
    context.bezierCurveTo(42, 202, 68, 147, 128, 144);
    context.bezierCurveTo(188, 147, 214, 202, 218, 310);
    context.closePath();
    context.fill();
    context.fillStyle = '#d4a17c';
    context.fillRect(111, 119, 34, 42);
    return canvas.toDataURL('image/png').split(',')[1];
  });
  await page.locator('input[type="file"]').setInputFiles({ name: 'segmentation-test.png', mimeType: 'image/png', buffer: Buffer.from(imageData, 'base64') });
  const removeButton = page.getByRole('button', { name: /Remove background/ });
  await removeButton.waitFor({ state: 'visible', timeout: 20_000 });
  await page.locator('select[aria-label="Segmentation model"]').selectOption(modelKind);
  assert.equal(await page.locator('select[aria-label="Segmentation model"]').inputValue(), modelKind);
  await removeButton.click();
  const segmentationStartedAt = Date.now();
  const refineButton = page.getByRole('button', { name: 'Refine mask' });
  await refineButton.waitFor({ state: 'visible', timeout: 120_000 });
  const segmentationMilliseconds = Date.now() - segmentationStartedAt;
  await page.getByRole('button', { name: 'Restore original' }).waitFor({ state: 'visible' });
  await page.waitForTimeout(800);
  const saved = await page.evaluate(async () => {
    const projects = await (await fetch('/api/projects')).json();
    return projects.flatMap((project) => project.nodes ?? []).find((node) => node.name.includes('segmentation-test.png'));
  });
  assert.ok(saved?.originalSrc, 'the source image must be retained for recovery');
  assert.ok(saved?.maskSrc, 'the generated segmentation mask must be persisted');
  const quality = await page.evaluate(async (maskUrl) => {
    const maskImage = new Image();
    maskImage.src = maskUrl;
    await maskImage.decode();
    const width = 256;
    const height = 320;
    const maskCanvas = document.createElement('canvas');
    maskCanvas.width = width;
    maskCanvas.height = height;
    const maskContext = maskCanvas.getContext('2d', { willReadFrequently: true });
    if (!maskContext) throw new Error('Mask quality canvas unavailable');
    maskContext.drawImage(maskImage, 0, 0, width, height);
    const actual = maskContext.getImageData(0, 0, width, height).data;
    const expectedCanvas = document.createElement('canvas');
    expectedCanvas.width = width;
    expectedCanvas.height = height;
    const expectedContext = expectedCanvas.getContext('2d', { willReadFrequently: true });
    if (!expectedContext) throw new Error('Reference canvas unavailable');
    expectedContext.fillStyle = '#fff';
    expectedContext.beginPath();
    expectedContext.ellipse(128, 77, 43, 52, 0, 0, Math.PI * 2);
    expectedContext.fill();
    expectedContext.beginPath();
    expectedContext.moveTo(38, 310);
    expectedContext.bezierCurveTo(42, 202, 68, 147, 128, 144);
    expectedContext.bezierCurveTo(188, 147, 214, 202, 218, 310);
    expectedContext.closePath();
    expectedContext.fill();
    expectedContext.fillRect(111, 119, 34, 42);
    const expected = expectedContext.getImageData(0, 0, width, height).data;
    let intersection = 0;
    let union = 0;
    let foregroundPixels = 0;
    for (let offset = 0; offset < actual.length; offset += 4) {
      const actualForeground = actual[offset] >= 128;
      const expectedForeground = expected[offset] > 0;
      if (actualForeground) foregroundPixels += 1;
      if (actualForeground || expectedForeground) union += 1;
      if (actualForeground && expectedForeground) intersection += 1;
    }
    return { iou: union ? intersection / union : 0, foregroundPixels };
  }, saved.maskSrc);
  assert.ok(quality.foregroundPixels > 1000, 'the model should retain a substantial subject');
  assert.ok(quality.iou >= 0.55, `synthetic portrait mask IoU ${quality.iou.toFixed(3)} is below the acceptance floor`);
  await refineButton.click();
  const maskCanvas = page.locator('.mask-editor-modal canvas');
  await maskCanvas.waitFor({ state: 'visible', timeout: 20_000 });
  const tools = page.locator('.mask-editor-tools button');
  const undoButton = tools.nth(2);
  const redoButton = tools.nth(3);
  assert.equal(await undoButton.isDisabled(), true);
  await maskCanvas.click({ position: { x: 24, y: 24 } });
  assert.equal(await undoButton.isDisabled(), false, 'manual mask strokes should enable undo');
  await undoButton.click();
  assert.equal(await redoButton.isDisabled(), false, 'undo should enable redo');
  await redoButton.click();
  await page.getByRole('button', { name: 'Apply transparent mask' }).click();
  await page.locator('.mask-editor-modal').waitFor({ state: 'detached', timeout: 30_000 });
  await page.waitForTimeout(800);
  const refined = await page.evaluate(async () => {
    const projects = await (await fetch('/api/projects')).json();
    return projects.flatMap((project) => project.nodes ?? []).find((node) => node.name.includes('segmentation-test.png'));
  });
  assert.ok(refined?.maskSrc, 'the refined mask should remain attached to the image');
  assert.deepEqual(failures, [], `Browser errors: ${failures.join(' | ')}`);
  assert.deepEqual(modelResponses.filter((response) => response.contentType?.includes('text/html')), [], `Model requests must not resolve to the app HTML document: ${JSON.stringify(modelResponses)}`);
  console.log(JSON.stringify({ model: modelKind === 'universal' ? 'bundled local BiRefNet Lite' : 'bundled local MODNet', segmentationMilliseconds, syntheticSubjectIoU: quality.iou, maskForegroundPixels: quality.foregroundPixels, sourcePreserved: Boolean(saved.originalSrc), maskStored: Boolean(saved.maskSrc), manualMaskUndoRedo: true, refinedMaskSaved: Boolean(refined.maskSrc), modelResponses }, null, 2));
} catch (error) {
  console.error(JSON.stringify({ modelKind, dialogs, failures, failedResponses, modelResponses, inspector: await page.locator('.inspector').innerText().catch(() => ''), status: await page.locator('.app-status').innerText().catch(() => '') }, null, 2));
  throw error;
} finally {
  await browser.close();
}
